// @vitest-environment happy-dom
/**
 * 2.1.26 (M13 L11 `m13l11sc`) — `useVersionDiff(type, slug, fromId, toId)`
 * returns the SEMANTIC delta of two versions: the `{ op, changes }` envelope the
 * host generates from the type's logical schema (operations on fields and on
 * collection items), never text lines.
 *
 * The served body is produced by the host's own engine (`diffFromSchema`, the
 * generator `diffEntity` runs for every type) over a logical-schema fixture, so
 * what the hook is asserted to return is exactly what the host generates — the
 * hook adds nothing and reshapes nothing. The route side (`host.diff` wiring,
 * payload upgrade, envelope) is pinned in `entities-router.test.ts`.
 */
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { act, createElement } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { useVersionDiff } from './useVersions.js';
import { diffFromSchema } from '../../server/serialization/schema-diff.js';
import type { FieldNode } from '../../shared/plugin-host/data-schema.js';
import type { RawDeltaEntityChange } from '../../shared/entities.js';

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

/** A logical schema: one scalar and one value collection matched by `name`. */
const schema: Record<string, FieldNode> = {
  description: { type: 'string' },
  fields: {
    type: 'collection',
    collection: { kind: 'value', identity: ['name'] },
    item: {
      type: 'object',
      fields: { name: { type: 'string' }, type: { type: 'string' } },
    },
  },
};

const v1 = { description: 'v1', fields: [{ name: 'id', type: 'string' }] };
const v2 = {
  description: 'v2',
  fields: [
    { name: 'id', type: 'number' },
    { name: 'email', type: 'string' },
  ],
};

/** The closed eight-operation dictionary of `EntityDiff.changes`. */
const DIFF_OPS = new Set([
  'field_changed',
  'field_changed_opaque',
  'item_added',
  'item_removed',
  'item_modified',
  'item_rekeyed',
  'tag_added',
  'tag_removed',
]);

let host: HTMLDivElement;
let root: Root;

beforeEach(() => {
  host = document.createElement('div');
  document.body.appendChild(host);
  root = createRoot(host);
});

afterEach(() => {
  act(() => root.unmount());
  host.remove();
  vi.unstubAllGlobals();
});

describe('useVersionDiff', () => {
  it('[ac:ac-useversiondiff-type-slug-fromid-toid] returns the semantic delta of two versions generated by the host from the logical schema — field and collection-item operations, not text lines', async () => {
    const served: RawDeltaEntityChange = {
      type: 'dto',
      slug: 'user-dto',
      op: 'updated',
      changes: diffFromSchema(schema, v1, v2),
    };
    const fetchMock = vi.fn(async (input: unknown) => {
      const url = String(input);
      if (url.endsWith('/entities/dto/user-dto/versions/1/diff/2')) {
        return new Response(JSON.stringify(served), {
          status: 200,
          headers: { 'Content-Type': 'application/json' },
        });
      }
      return new Response(JSON.stringify({ error: { code: 'NOT_FOUND', message: url } }), { status: 404 });
    });
    vi.stubGlobal('fetch', fetchMock);

    const seen: { data?: unknown } = {};
    function Probe() {
      const q = useVersionDiff('dto', 'user-dto', 1, 2);
      seen.data = q.data;
      return null;
    }
    const qc = new QueryClient({ defaultOptions: { queries: { retry: false } } });

    await act(async () => {
      root.render(createElement(QueryClientProvider, { client: qc }, createElement(Probe)));
    });
    await vi.waitFor(() => expect(seen.data).toBeDefined());

    // One request, to the per-entity version-diff route for (fromId, toId).
    expect(fetchMock).toHaveBeenCalledTimes(1);
    expect(String(fetchMock.mock.calls[0]![0])).toMatch(/\/entities\/dto\/user-dto\/versions\/1\/diff\/2$/);

    const delta = seen.data as RawDeltaEntityChange;
    // Exactly what the host generated — the hook neither reshapes nor renders it.
    expect(delta).toEqual(served);
    expect(delta.op).toBe('updated');

    // Semantic: an operation on a field and operations on collection items,
    // matched by the identity the schema declares.
    expect(delta.changes).toContainEqual({ op: 'field_changed', path: 'description', from: 'v1', to: 'v2' });
    expect(delta.changes).toContainEqual({
      op: 'item_modified',
      path: 'fields',
      identity: { name: 'id' },
      changes: [{ op: 'field_changed', path: 'fields[].type', from: 'string', to: 'number' }],
    });
    expect(delta.changes).toContainEqual({
      op: 'item_added',
      path: 'fields',
      identity: { name: 'email' },
      item: { name: 'email', type: 'string' },
    });

    // Not text lines: every entry is an op of the closed delta dictionary,
    // none carries a `line` (the `DiffView.hunks` add/del/ctx vocabulary).
    for (const change of delta.changes) {
      expect(DIFF_OPS.has(change.op)).toBe(true);
      expect(change).not.toHaveProperty('line');
    }
  });
});
